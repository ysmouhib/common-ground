"""Command line: ``python -m commonground <command>``.

    check     decide one argument given as formulas
    analyze   conflicts, concessions and justifications for a debate file
    folio     run the FOLIO benchmark (reference formalizations, or a language model)
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

from . import argmap, bench, folio, lean
from .fol import Not, ParseError, parse
from .verdict import decide


def _check(args) -> int:
    try:
        premises = [parse(p) for p in args.premise]
        conclusion = parse(args.conclusion)
    except ParseError as exc:
        print(f"not a formula: {exc}", file=sys.stderr)
        return 2
    verdict = decide(premises, conclusion, args.timeout_ms)
    out = verdict.to_json()
    if args.lean and verdict.label in ("True", "False"):
        lean_bin = lean.find_lean()
        if lean_bin is None:
            out["lean"] = f"no Lean {lean.TOOLCHAIN} found (set LEAN_BIN)"
        else:
            goal = conclusion if verdict.label == "True" else Not(conclusion)
            certificate = lean.certify([(premises, goal)], lean_bin)[0]
            out["lean"] = {"certified": certificate.accepted, "axioms": certificate.axioms,
                           "reason": certificate.reason}
    print(json.dumps(out, indent=2, ensure_ascii=False))
    return 0


TS_HEADER = """// Generated by `python -m commonground analyze {source} --out {target}`.
// Do not edit: engine/tests/test_generated.py fails when this file is out of date.
export const analysis = {body} as const;

export type DebateAnalysis = typeof analysis;
"""


def render_analysis(debate: str, out: str | None, timeout_ms: int = 5000) -> str:
    _, statements = argmap.load_debate(debate)
    body = json.dumps(argmap.analyze(statements, timeout_ms), indent=2, ensure_ascii=False)
    if out and out.endswith(".ts"):
        return TS_HEADER.format(source=Path(debate).as_posix(), target=Path(out).as_posix(), body=body)
    return body + "\n"


def _analyze(args) -> int:
    text = render_analysis(args.debate, args.out, args.timeout_ms)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
    else:
        print(text, end="")
    return 0


def _folio(args) -> int:
    data_file = folio.fetch(Path(args.data))
    out_dir = Path(args.out)
    if args.mode == "reference":
        lean_bin = lean.find_lean() if args.lean else None
        if args.lean and lean_bin is None:
            print(f"no Lean {lean.TOOLCHAIN} found (set LEAN_BIN)", file=sys.stderr)
            return 2
        summary = bench.reference(data_file, out_dir, lean_bin, args.timeout_ms)
    else:
        from .formalize import OpenAICompatible
        key = os.environ.get(args.api_key_env, "")
        if not (args.base_url and args.model and key):
            print(f"--base-url, --model and the {args.api_key_env} environment variable are required", file=sys.stderr)
            return 2
        client = OpenAICompatible(args.base_url, args.model, key)
        summary = bench.with_model(data_file, out_dir, client, args.mode, args.limit, args.timeout_ms)
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="commonground", description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--timeout-ms", type=int, default=5000, help="solver limit per satisfiability question")
    commands = parser.add_subparsers(dest="command", required=True)

    check = commands.add_parser("check", help="decide one argument")
    check.add_argument("--premise", action="append", default=[], help="a formula; repeat for each premise")
    check.add_argument("--conclusion", required=True)
    check.add_argument("--lean", action="store_true", help="also ask the Lean kernel to certify the verdict")
    check.set_defaults(run=_check)

    analyze = commands.add_parser("analyze", help="analyse a debate file")
    analyze.add_argument("debate")
    analyze.add_argument("--out")
    analyze.set_defaults(run=_analyze)

    fol = commands.add_parser("folio", help="run the FOLIO benchmark")
    fol.add_argument("--data", default="data/FOLIO", help="where the dataset repository is (cloned if absent)")
    fol.add_argument("--out", required=True)
    fol.add_argument("--mode", choices=("reference", "llm", "direct"), default="reference")
    fol.add_argument("--lean", action="store_true", help="reference mode: certify verdicts with Lean")
    fol.add_argument("--base-url")
    fol.add_argument("--model")
    fol.add_argument("--api-key-env", default="LLM_API_KEY", help="name of the variable holding the key")
    fol.add_argument("--limit", type=int)
    fol.set_defaults(run=_folio)

    args = parser.parse_args(argv)
    return args.run(args)


if __name__ == "__main__":
    sys.exit(main())
